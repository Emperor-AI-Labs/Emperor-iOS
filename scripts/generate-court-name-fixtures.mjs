#!/usr/bin/env node
// Regenerates the golden data for how a court-printed name is tidied for display.
//
//   node scripts/generate-court-name-fixtures.mjs <path-to-emperor-ai> [--check]
//
// The platform's `src/lib/courtNames.js` (`tidyCourtName`) turns a cause title printed in
// capitals into the name a matter made from that case is given, and the Matters list shows a
// tracked case under the same name. `CourtNames.swift` is held to that file's answers. The module
// has no imports, so it is loaded as it is.
//
// Output: `Tests/EmperorCoreTests/CourtNamesGolden.swift`. `--check` writes nothing and exits 1
// if the file would change.

import { pathToFileURL, fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

const platform = process.argv[2]
const checkOnly = process.argv.includes('--check')
if (!platform || !fs.existsSync(path.join(platform, 'src/lib/courtNames.js'))) {
  console.error('usage: generate-court-name-fixtures.mjs <path-to-emperor-ai> [--check]')
  process.exit(2)
}
const lib = await import(pathToFileURL(path.resolve(platform, 'src/lib/courtNames.js')).href)
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  '../Tests/EmperorCoreTests/CourtNamesGolden.swift')

const inputs = [
  'M/S PSTGEMS PRIVATE LIMITED VS. ALISHA ENTERPRISES',
  'STATE V. RAM KUMAR',
  'K. V. RAO VS UNION OF INDIA',
  'S/O V. K. SHARMA',
  'RAJESH KUMAR AND ANR. VERSUS STATE OF U.P. AND ORS.',
  'UOI V/S GNCTD THROUGH ITS CHIEF SECRETARY',
  'ABC INFRA LLP VS. HDFC BANK LTD.',
  'Menon vs. Union of India',
  'NARESH  \n  GUPTA   vs   SBI',
  'ICICI BANK v ROHIT',
  'CO. OPERATIVE SOCIETY VS DR. MEHTA',
  'RK ENTERPRISES VS PS TRADERS',
  'M/S. O\'BRIEN & SONS VS STATE OF J&K',
  'W.P.(C) 4412/2025 RAMESH VS UOI',
  'V',
  '',
  'ABC',
  'X '.repeat(120).trim(),
]

const golden = inputs.flatMap((raw) => [
  { raw, title: true, expected: lib.tidyCourtName(raw, { title: true }) },
  { raw, title: false, expected: lib.tidyCourtName(raw) },
])

const json = JSON.stringify(golden, null, 2)
if (json.includes('"""#')) throw new Error('fixture would terminate the Swift raw string early')

const swift = `// Generated by scripts/generate-court-name-fixtures.mjs from the platform's
// src/lib/courtNames.js. Do not edit by hand — regenerate it.

enum CourtNamesGolden {
    static let json = #"""
${json}
"""#
}
`

const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null
if (before === swift) {
  console.log('court-name fixtures: up to date')
  process.exit(0)
}
if (checkOnly) {
  console.error('court-name fixtures: out of date — rerun without --check')
  process.exit(1)
}
fs.writeFileSync(out, swift)
console.log(`court-name fixtures: wrote ${golden.length} cases`)
