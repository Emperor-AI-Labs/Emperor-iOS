#!/usr/bin/env node
// Regenerates Sources/EmperorCore/RecordTokens.swift from the Record design tokens.
//
//   node scripts/generate-record-tokens.mjs [--check]
//
// The mobile design ("Emperor Record", v1.0) ships one `tokens.json` for both phones: every
// colour, gradient, type size, radius, spacing step, layout size, curve and duration. A copy is
// kept at Design/record-tokens.json, and this turns it into Swift so the app and the JSON can
// never drift apart — nothing in the app restates a token by hand.
//
// Only the iOS variant of a platform-split token is emitted (`{ "ios": 20, "android": 16 }`
// becomes `20`). Colours become `PaletteColor`, so `PaletteTests` can measure every pairing the
// app draws in the Foundation-only core; the app layer maps them to SwiftUI once, in `Theme`.
//
// `--check` writes nothing and exits 1 if the Swift file differs from what the JSON produces —
// the way to ask "did someone edit the generated file, or the tokens without regenerating?"

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const input = path.join(root, 'Design/record-tokens.json')
const output = path.join(root, 'Sources/EmperorCore/RecordTokens.swift')
const checkOnly = process.argv.includes('--check')

const tokens = JSON.parse(fs.readFileSync(input, 'utf8'))

const ios = (value) => (value && typeof value === 'object' && 'ios' in value ? value.ios : value)
const num = (value) => {
  const n = Number(value)
  if (!Number.isFinite(n)) throw new Error(`not a number: ${value}`)
  return Number.isInteger(n) ? `${n}` : `${n}`
}

/// `#RRGGBB` or `rgba(r, g, b, a)` → a `PaletteColor` expression.
function colour(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value)
  if (hex) return `PaletteColor(hex: 0x${hex[1].toUpperCase()})`
  const rgba = /^rgba\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*\)$/.exec(value)
  if (rgba) {
    const h = [rgba[1], rgba[2], rgba[3]]
      .map((c) => Number(c).toString(16).padStart(2, '0').toUpperCase())
      .join('')
    return `PaletteColor(hex: 0x${h}, opacity: ${num(rgba[4])})`
  }
  throw new Error(`unrecognised colour: ${value}`)
}

const colourNames = Object.keys(tokens.color.light)
for (const name of colourNames) {
  if (!(name in tokens.color.dark)) throw new Error(`dark is missing ${name}`)
}

const lines = []
const out = (s = '') => lines.push(s)

out('// Generated by scripts/generate-record-tokens.mjs from Design/record-tokens.json.')
out('// Do not edit by hand: change the JSON and regenerate.')
out()
out('import Foundation')
out()
out(`/// The Record design tokens — "${tokens.meta.name}", v${tokens.meta.version} (${tokens.meta.date}).`)
out('///')
out('/// The iOS value of every platform-split token. Colours are `PaletteColor` so the contrast of')
out('/// every pairing can be tested here, without a device; `Palette` and `Theme` are built on them.')
out('enum RecordTokens {')
out()
out('    static let version = "' + tokens.meta.version + '"')
out()
out('    // MARK: - Colour')
out()
out('    /// One appearance\'s colour roles, named as the design names them.')
out('    struct ColorSet: Equatable, Sendable {')
for (const name of colourNames) out(`        let ${name}: PaletteColor`)
out('    }')
out()
for (const scheme of ['light', 'dark']) {
  out(`    static let ${scheme} = ColorSet(`)
  colourNames.forEach((name, i) => {
    const sep = i === colourNames.length - 1 ? ')' : ','
    out(`        ${name}: ${colour(tokens.color[scheme][name])}${sep}`)
  })
  out()
}
out('    // MARK: - Gradients')
out()
out('    /// A two-stop linear gradient. `angle` is CSS degrees: 135 runs top-leading to bottom-trailing.')
out('    struct GradientStops: Equatable, Sendable {')
out('        let start: PaletteColor')
out('        let end: PaletteColor')
out('        let angle: Double')
out('    }')
out()
out('    enum Gradient {')
for (const [name, g] of Object.entries(tokens.gradient)) {
  const angle = g.angle ?? 135
  for (const scheme of ['light', 'dark']) {
    const cap = scheme[0].toUpperCase() + scheme.slice(1)
    out(`        static let ${name}${cap} = GradientStops(`)
    out(`            start: ${colour(g[scheme][0])}, end: ${colour(g[scheme][1])}, angle: ${num(angle)})`)
  }
}
out('    }')
out()
out('    // MARK: - Type')
out()
out('    enum FontRole: Sendable, Equatable {')
out('        /// Instrument Serif — large titles, greetings, item numbers, document titles.')
out('        case display')
out('        /// Plus Jakarta Sans — everything else.')
out('        case ui')
out('    }')
out()
out('    /// One step of the type scale, at the default Dynamic Type size.')
out('    struct TextStyle: Equatable, Sendable {')
out('        let role: FontRole')
out('        /// CSS weight: 400, 500, 600 or 700.')
out('        let weight: Int')
out('        let size: Double')
out('        /// Line height, where the scale gives one.')
out('        let lineHeight: Double?')
out('        /// Letter spacing as a fraction of the size (CSS `em`).')
out('        let tracking: Double')
out('        let uppercase: Bool')
out('    }')
out()
out('    enum Typography {')
for (const [name, t] of Object.entries(tokens.type)) {
  const v = t.ios ?? t
  const size = v.size ?? t.size
  const line = v.line ?? t.line
  const weight = v.weight ?? t.weight
  const role = t.font === 'display' ? '.display' : '.ui'
  out(`        static let ${name} = TextStyle(`)
  out(`            role: ${role}, weight: ${weight}, size: ${num(size)}, lineHeight: ${line === undefined ? 'nil' : num(line)},`)
  out(`            tracking: ${num(t.tracking ?? 0)}, uppercase: ${t.case === 'upper'})`)
}
out('    }')
out()
out('    // MARK: - Shape, space, layout')
out()
out('    enum Radius {')
for (const [name, r] of Object.entries(tokens.radius)) {
  if (Array.isArray(r)) {
    out(`        /// Top-leading, top-trailing, bottom-trailing, bottom-leading.`)
    out(`        static let ${name}: [Double] = [${r.map(num).join(', ')}]`)
  } else {
    out(`        static let ${name}: Double = ${num(ios(r))}`)
  }
}
out('    }')
out()
out('    enum Space {')
for (const [name, s] of Object.entries(tokens.space)) out(`        static let ${name}: Double = ${num(s)}`)
out('    }')
out()
out('    enum Layout {')
for (const [name, l] of Object.entries(tokens.layout)) {
  const type = Number.isInteger(ios(l)) && name.endsWith('Lines') ? 'Int' : 'Double'
  out(`        static let ${name}: ${type} = ${num(ios(l))}`)
}
out('    }')
out()
out('    // MARK: - Motion')
out()
out('    /// A cubic Bézier timing curve, as CSS `cubic-bezier(x1, y1, x2, y2)`.')
out('    struct Curve: Equatable, Sendable {')
out('        let x1: Double, y1: Double, x2: Double, y2: Double')
out('    }')
out()
out('    enum Motion {')
for (const name of ['easeOut', 'easeInOut', 'easePop']) {
  const [a, b, c, d] = tokens.motion[name]
  out(`        static let ${name} = Curve(x1: ${num(a)}, y1: ${num(b)}, x2: ${num(c)}, y2: ${num(d)})`)
}
out()
out('        /// Durations, in seconds.')
out('        enum Duration {')
for (const [name, ms] of Object.entries(tokens.motion.duration)) {
  out(`            static let ${name}: Double = ${num(ms / 1000)}`)
}
const fade = /(\d+)\s*ms/.exec(tokens.motion.reduceMotion)
if (!fade) throw new Error('reduceMotion names no duration')
out(`            /// Reduce Motion: "${tokens.motion.reduceMotion}".`)
out(`            static let reduceMotionCrossFade: Double = ${num(Number(fade[1]) / 1000)}`)
out('        }')
out('    }')
out()
out('    // MARK: - Elevation')
out()
out('    struct Shadow: Equatable, Sendable {')
out('        let y: Double')
out('        let blur: Double')
out('        let color: PaletteColor')
out('    }')
out()
out('    enum Elevation {')
for (const [level, css] of Object.entries(tokens.elevation)) {
  const m = /^0\s+(\d+)px\s+(\d+)px\s+(rgba\([^)]*\))$/.exec(css)
  if (!m) throw new Error(`unrecognised shadow: ${css}`)
  out(`        static let level${level} = Shadow(y: ${num(m[1])}, blur: ${num(m[2])}, color: ${colour(m[3].replace(/\s+/g, ''))})`)
}
out('    }')
out('}')
out()

const swift = lines.join('\n')
if (checkOnly) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : ''
  if (current !== swift) {
    console.error('RecordTokens.swift is out of date — run scripts/generate-record-tokens.mjs')
    process.exit(1)
  }
  console.log('RecordTokens.swift matches Design/record-tokens.json')
} else {
  fs.writeFileSync(output, swift)
  console.log(`wrote ${path.relative(root, output)}`)
}
