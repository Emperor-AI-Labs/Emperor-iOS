#!/usr/bin/env node
// Regenerates the golden data for how the Billing page prints money, dates and a plan's standing.
//
//   node scripts/generate-billing-fixtures.mjs <path-to-emperor-ai> [--check]
//
// The platform's `src/pages/Billing.jsx` keeps its formatting in plain functions at the top of the
// file — `fmtPaise`, `toDate`, `fmtDate`, `daysLeft`, `SOURCE_WORDS`, `ORDER_STATUS` and
// `statusOf` — ahead of the first component. That block has no imports of its own, so it is cut
// out of the page and evaluated as it is; `BillingMoney` and `BillingStanding` are held to its
// answers. Dates are read in India (`TZ=Asia/Kolkata`), which is where this app formats them.
// `Date.now` is pinned so the standing is the same on every run.
//
// Output: `Tests/EmperorCoreTests/BillingGolden.swift`. `--check` writes nothing and exits 1 if
// the file would change.

import { fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

process.env.TZ = 'Asia/Kolkata'

const platform = process.argv[2]
const checkOnly = process.argv.includes('--check')
const page = platform && path.join(platform, 'src/pages/Billing.jsx')
if (!page || !fs.existsSync(page)) {
  console.error('usage: generate-billing-fixtures.mjs <path-to-emperor-ai> [--check]')
  process.exit(2)
}
const source = fs.readFileSync(page, 'utf8')
const start = source.indexOf('const fmtPaise')
const end = source.indexOf('function Row(')
if (start < 0 || end < start) throw new Error('Billing.jsx no longer has the helpers this reads')
const block = source.slice(start, end)

const NOW = Date.parse('2026-10-19T06:30:00.000Z')
const realNow = Date.now
Date.now = () => NOW
// eslint-disable-next-line no-new-func
const lib = new Function(`${block}\nreturn { fmtPaise, fmtDate, daysLeft, statusOf, SOURCE_WORDS, ORDER_STATUS }`)()

const paise = [0, 1, 5, 99, 100, 150, 299900, 353882, 999900, 1234567, 10000000, 12345678900, -50, -150000]
const money = paise.map((p) => ({ paise: p, text: lib.fmtPaise(p) }))

const dates = [
  '2026-10-19T06:30:00.000Z',
  '2026-10-18 20:00:00',
  '2026-11-01T18:29:59.000Z',
  '2027-01-05 00:00:00',
  '2026-02-28T23:00:00Z',
].map((raw) => ({ raw, text: lib.fmtDate(raw), daysLeft: lib.daysLeft(raw) }))

const plans = [
  null,
  { planSource: null, expiresAt: '2026-12-01T00:00:00.000Z' },
  { planSource: 'purchase', expired: true, expiresAt: '2026-09-01T00:00:00.000Z' },
  { planSource: 'grandfathered', expired: false, expiresAt: null },
  { planSource: 'purchase', expired: false, expiresAt: '2026-10-19T06:30:00.000Z' },
  { planSource: 'purchase', expired: false, expiresAt: '2026-10-19T12:00:00.000Z' },
  { planSource: 'purchase', expired: false, expiresAt: '2026-10-20T06:00:00.000Z' },
  { planSource: 'coupon', expired: false, expiresAt: '2026-10-25T06:30:00.000Z' },
  { planSource: 'admin', expired: false, expiresAt: '2026-11-01T06:30:00.000Z' },
  { planSource: 'admin', expired: false, expiresAt: '2026-11-02T06:30:00.000Z' },
  { planSource: 'purchase', expired: false, expiresAt: '2027-10-19 06:30:00' },
].map((plan) => ({ plan, standing: lib.statusOf(plan) }))

Date.now = realNow

const golden = {
  now: new Date(NOW).toISOString(),
  money,
  dates,
  standings: plans,
  sourceWords: lib.SOURCE_WORDS,
  orderStatus: Object.fromEntries(Object.entries(lib.ORDER_STATUS).map(([k, v]) => [k, v.text])),
}

const json = JSON.stringify(golden, null, 2)
if (json.includes('"""#')) throw new Error('fixture would terminate the Swift raw string early')

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  '../Tests/EmperorCoreTests/BillingGolden.swift')
const swift = `// Generated by scripts/generate-billing-fixtures.mjs from the platform's
// src/pages/Billing.jsx. Do not edit by hand — regenerate it.

enum BillingGolden {
    static let json = #"""
${json}
"""#
}
`

const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null
if (before === swift) {
  console.log('billing fixtures: up to date')
  process.exit(0)
}
if (checkOnly) {
  console.error('billing fixtures: out of date — rerun without --check')
  process.exit(1)
}
fs.writeFileSync(out, swift)
console.log(`billing fixtures: wrote ${money.length} amounts, ${dates.length} dates, ${plans.length} standings`)
