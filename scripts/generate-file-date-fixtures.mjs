#!/usr/bin/env node
// Regenerates the My Files date-label golden cases from the platform's own source.
//
//   node scripts/generate-file-date-fixtures.mjs <path-to-emperor-ai> [--check]
//
// My Files labels a document's date "Today", "Yesterday" or "3 Oct 2026", in India. The rule is
// the web's `relDay` (src/pages/MyFilesPage.jsx) over its `istDayKey` and `fmtDate`
// (src/lib/datetime.js), and `FileBrowser.dayLabel` is held to what those produce under Node —
// not to anyone's reading of them. Two details are easy to get wrong by eye: the day boundary is
// India's midnight, not UTC's or the device's, and `en-IN` abbreviates September as "Sept".
//
// `relDay` lives inside a page component, so it is lifted out of the JSX by its declaration and
// evaluated against the real `istDayKey` and `fmtDate`. If the platform rewrites it, the match
// below fails loudly rather than producing stale cases.
//
// The clock is pinned to 3 October 2026, 12:00 in India; `FileDateGolden.nowMillis` is the same
// instant. `--check` writes nothing and exits 1 if the committed file differs.

import { pathToFileURL, fileURLToPath } from 'node:url'
import fs from 'node:fs'
import path from 'node:path'

const platform = process.argv[2]
const checkOnly = process.argv.includes('--check')
if (!platform || !fs.existsSync(path.join(platform, 'src/lib/datetime.js'))) {
  console.error('usage: generate-file-date-fixtures.mjs <path-to-emperor-ai> [--check]')
  process.exit(2)
}

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  '../Tests/EmperorCoreTests/FileDateGolden.swift')

// Pinned clock: 2026-10-03 12:00 IST.
const NOW = Date.UTC(2026, 9, 3, 6, 30, 0)
const RealDate = Date
globalThis.Date = class extends RealDate {
  constructor(...args) { if (args.length === 0) super(NOW); else super(...args) }
  static now() { return NOW }
}

const datetime = await import(pathToFileURL(path.join(platform, 'src/lib/datetime.js')).href)

const page = fs.readFileSync(path.join(platform, 'src/pages/MyFilesPage.jsx'), 'utf8')
const declaration = page.match(/function relDay\(v\) \{[\s\S]*?\n\}/)
if (!declaration) {
  console.error('relDay was not found in src/pages/MyFilesPage.jsx — the platform has changed shape')
  process.exit(1)
}
// eslint-disable-next-line no-new-func
const relDay = new Function('istDayKey', 'fmtDate', `${declaration[0]}\nreturn relDay`)(
  datetime.istDayKey, datetime.fmtDate)

// Instants chosen for the boundaries: either side of India's midnight today and yesterday, the
// UTC midnight that is not a day boundary in India, every month once (for "Sept"), and a year
// turning over in India before it does in UTC.
const instants = [
  '2026-10-03T06:30:00.000Z', // now
  '2026-10-02T18:31:00.000Z', // 00:01 IST today
  '2026-10-03T18:29:00.000Z', // 23:59 IST today, later than now
  '2026-10-02T18:29:00.000Z', // 23:59 IST yesterday
  '2026-10-01T18:30:00.000Z', // 00:00 IST yesterday
  '2026-10-01T18:29:00.000Z', // 23:59 IST two days ago
  '2026-10-03T00:00:00.000Z', // UTC midnight: 05:30 IST today
  '2026-10-02T00:00:00.000Z', // UTC midnight: 05:30 IST yesterday
  '2026-10-04T06:30:00.000Z', // tomorrow
  '2025-12-31T18:45:00.000Z', // 1 Jan 2026 in India, still 2025 in UTC
  ...Array.from({ length: 12 }, (_, m) => new RealDate(RealDate.UTC(2026, m, 15, 6)).toISOString()),
]

const cases = instants.map(iso => {
  const millis = new RealDate(iso).getTime()
  return { iso, millis, label: relDay(millis) }
})

const swift = `// Generated by scripts/generate-file-date-fixtures.mjs from the platform's own
// src/lib/datetime.js (istDayKey, fmtDate) and src/pages/MyFilesPage.jsx (relDay), run under
// Node with the clock pinned. Do not edit by hand — regenerate.

enum FileDateGolden {
    /// 2026-10-03 12:00 in India.
    static let nowMillis: Double = ${NOW}

    static let cases: [(millis: Double, label: String)] = [
${cases.map(c => `        (${c.millis}, ${JSON.stringify(c.label)}), // ${c.iso}`).join('\n')}
    ]
}
`

if (checkOnly) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (current !== swift) {
    console.error('FileDateGolden.swift is out of date with the platform')
    process.exit(1)
  }
  console.log('FileDateGolden.swift matches the platform')
} else {
  fs.writeFileSync(out, swift)
  console.log(`wrote ${cases.length} cases to ${path.relative(process.cwd(), out)}`)
}
