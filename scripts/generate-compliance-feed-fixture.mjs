#!/usr/bin/env node
// Regenerates the golden `GET /compliance-calendar` response the Corporate Calendar is tested
// against.
//
//   node scripts/generate-compliance-feed-fixture.mjs <path-to-emperor-ai> [--check]
//
// The response is not typed out by hand. It is produced by the platform's own code path for that
// route — `lib/complianceCalendarFeed.js` → `db/schedule.js` — run under Node against the
// platform's own schema and seed rows (`db/schema.sql`, `db/seed_universal.sql`,
// `db/seed_conditional.sql`), loaded into Node's built-in SQLite. So every key, every null and
// every "N/A - …" placeholder is what the route really serialises.
//
// Two things are pinned so the fixture does not change daily:
//   - the clock: 3 October 2026, noon in India (the route computes each next due date from
//     "today", in the server's local zone, which is set to Asia/Kolkata here);
//   - two published circulars, applied through the platform's own `pipeline/publish.js`, so the
//     fixture carries the one state a seed cannot show: a date moved off its usual schedule. One
//     moves GSTR-3B, a fixed monthly return; the other dates DIR-12, an event-relative filing
//     that otherwise has no date at all without company context.
//
// The platform's `better-sqlite3` is replaced by `node:sqlite` (the database is passed in
// explicitly, so the stand-in is never constructed) — that is the only substitution.
//
// Output: `Tests/EmperorCoreTests/ComplianceFeedFixture.swift`, a Swift source file rather than a
// resource, so it needs no change to Package.swift or project.yml.

import { registerHooks } from 'node:module'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { DatabaseSync } from 'node:sqlite'
import fs from 'node:fs'
import path from 'node:path'

process.env.TZ = 'Asia/Kolkata'

const platform = process.argv[2]
const checkOnly = process.argv.includes('--check')
if (!platform || !fs.existsSync(path.join(platform, 'lib/complianceCalendarFeed.js'))) {
  console.error('usage: generate-compliance-feed-fixture.mjs <path-to-emperor-ai> [--check]')
  process.exit(2)
}
const root = path.resolve(platform)
const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)),
  '../Tests/EmperorCoreTests/ComplianceFeedFixture.swift')

registerHooks({
  resolve(specifier, context, next) {
    if (specifier === 'better-sqlite3') return { url: 'emperor-stub:sqlite', shortCircuit: true }
    return next(specifier, context)
  },
  load(url, context, next) {
    if (url === 'emperor-stub:sqlite') {
      return { format: 'module', source: 'export default class {}', shortCircuit: true }
    }
    // The platform's package.json may not declare "type": "module"; its sources are ESM.
    if (url.startsWith(pathToFileURL(root).href) && url.endsWith('.js')) {
      return { format: 'module', source: fs.readFileSync(fileURLToPath(url), 'utf8'), shortCircuit: true }
    }
    return next(url, context)
  },
})

// Pinned clock: 2026-10-03 12:00 IST. `publish()` stamps `last_verified_date` from `new Date()`.
const FIXED = Date.UTC(2026, 9, 3, 6, 30, 0)
const RealDate = Date
globalThis.Date = class extends RealDate {
  constructor(...args) { if (args.length === 0) super(FIXED); else super(...args) }
  static now() { return FIXED }
}

const db = new DatabaseSync(':memory:')
for (const file of ['schema.sql', 'seed_universal.sql', 'seed_conditional.sql']) {
  db.exec(fs.readFileSync(path.join(root, 'db', file), 'utf8'))
}

const { publish } = await import(pathToFileURL(path.join(root, 'pipeline/publish.js')).href)
publish({
  summary: 'GSTR-3B for September 2026 extended',
  source_citation: 'Illustrative circular for the fixture',
  published: [
    { compliance_id: 'GSTR3B', new_effective_date: '2026-10-25', change_type: 'deadline_extension', reasoning: 'fixture' },
    { compliance_id: 'DIR12', new_effective_date: '2026-10-20', change_type: 'deadline_extension', reasoning: 'fixture' },
  ],
  dropped: [],
}, 'fixture-1', null, 'CBIC', db)

const { getComplianceCalendarEvents } = await import(
  pathToFileURL(path.join(root, 'lib/complianceCalendarFeed.js')).href)
const rows = getComplianceCalendarEvents(db, new Date())

// Exactly what the route writes: `res.end(JSON.stringify(getComplianceCalendarEvents()))`.
// Pretty-printed only so the fixture can be read; whitespace is not part of the contract.
const json = JSON.stringify(JSON.parse(JSON.stringify(rows)), null, 2)
if (json.includes('"""#')) throw new Error('fixture would terminate the Swift raw string early')

const dated = rows.filter(r => r.dateKey).length
const swift = `// Generated by scripts/generate-compliance-feed-fixture.mjs from the platform's own
// lib/complianceCalendarFeed.js and db/ seed rows. Do not edit by hand — regenerate it.
//
// The body \`GET /compliance-calendar\` answers on ${ComplianceToday()}, with two published
// circulars applied (GSTR3B moved to 2026-10-25; DIR12 dated 2026-10-20). ${rows.length} rows, of which
// ${dated} carry a date.

enum ComplianceFeedFixture {
    /// The day, in India, the feed was computed for.
    static let today = "2026-10-03"
    static let rowCount = ${rows.length}
    static let datedRowCount = ${dated}

    static let json = #"""
${json}
"""#
}
`

function ComplianceToday() { return '3 October 2026 (IST)' }

const before = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null
if (before === swift) {
  console.log('compliance feed fixture: up to date')
  process.exit(0)
}
if (checkOnly) {
  console.error('compliance feed fixture: out of date — rerun without --check')
  process.exit(1)
}
fs.writeFileSync(out, swift)
console.log(`compliance feed fixture: wrote ${rows.length} rows (${dated} dated)`)
