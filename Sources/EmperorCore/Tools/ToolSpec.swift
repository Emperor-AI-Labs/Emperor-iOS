/// Formats a date the way the prompts do: `DD.MM.YYYY`, in India.
///
/// Every court date in this product means a day in India, and a tool that prints "as on" against
/// the device's zone tells someone travelling the wrong day.
enum ToolDate {
    static func indianFormat(_ date: Date) -> String {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = TimeZone(identifier: "Asia/Kolkata") ?? .gmt
        let parts = calendar.dateComponents([.day, .month, .year], from: date)
        return String(format: "%02d.%02d.%04d", parts.day ?? 1, parts.month ?? 1, parts.year ?? 1970)
    }
}
